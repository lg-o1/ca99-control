new Vue({
	el: '#app',
	data() {
		return initialState()
	},
	methods: {
		touchStart: function(event) {
			let touchObject = event.changedTouches[0];
			this.start_position_x = touchObject.pageX;
			this.start_position_y = touchObject.pageY;

			//document.interval = setInterval(function(){
			//	this.touch_time += 100;
			//	if(this.touch_time == 1000){
			//		clearInterval(document.interval);
			//		this.touch_time = 0;
			//		this.SettingWindow = true;
			//	}
			//}.bind(this), 100)
		},
		touchEnd: function(item) {
			let touchObject = event.changedTouches[0];
			this.end_position_x = touchObject.pageX;
			this.end_position_y = touchObject.pageY;
			this.dx = this.start_position_x - this.end_position_x;
			this.dy = this.start_position_y - this.end_position_y;

			let index1 = Math.floor((item.id-1)/6);
			let index2 = (item.id-1)%6;

			this.$set(this.lattice[index1][index2], 'count', this.lattice[index1][index2].count+1);
			if((this.dx < -10) || (this.dx > 10) || (this.dy < -10) || (this.dy > 10)){
				this.lattice[index1][index2].display = 'NG';
				this.lattice[index1][index2].ng = true;
			}else if((this.lattice[index1][index2].count >= 10) && (!this.lattice[index1][index2].ng)){
				this.lattice[index1][index2].display = 'OK';
				this.lattice[index1][index2].ok = true;
			}

			clearInterval(document.interval);
			this.touch_time = 0;
		},

		swipeStart: function(item) {
			event.preventDefault();

			let touchObject = event.changedTouches[0];
			this.start_position_x = touchObject.pageX;
			this.start_position_y = touchObject.pageY;

			this.start_index_y = Math.floor((item.id-1)/6);
			this.start_index_x = (item.id-1)%6;

			//document.interval = setInterval(function(){
			//	this.touch_time += 100;
			//	if(this.touch_time == 1000){
			//		clearInterval(document.interval);
			//		this.touch_time = 0;
			//		this.SettingWindow = true;
			//	}
			//}.bind(this), 100)
		},
		swipeMove: function() {
			clearInterval(document.interval);
			this.touch_time = 0;
		},
		swipeEnd: function(item) {
			let touchObject = event.changedTouches[0];
			this.end_position_x = touchObject.pageX;
			this.end_position_y = touchObject.pageY;
			this.dx = this.end_position_x - this.start_position_x;
			this.dy = this.end_position_y - this.start_position_y;

			// 横位置を求める
			for(let i=1;i<6;i++){
				if(this.end_position_x < screen.width/6*i){
					this.end_index_x = i-1;
					break;
				}else if(i == 5){
					this.end_index_x = 5;
					break;
				}
			}
			// 縦位置を求める
			for(let j=1;j<9;j++){
				if(this.end_position_y < screen.height/9*j){
					this.end_index_y = j-1;
					break;
				}else if(j == 8){
					this.end_index_y = 8;
				}
			}
			//tableのidを求める
			this.end_id = 6 * this.end_index_y + (this.end_index_x + 1);

			if(this.start_index_x == this.end_index_x){	// 縦線の場合
				if(this.dy > screen.height/9*8){	// 縦のマスすべて通っている場合のみスワイプ判定する
					if((this.dx < -10) || (this.dx > 10)){	// 縦NG
						for(let j=0;j<9;j++){
							this.lattice[j][this.start_index_x].verticalng = true;
						}
					}else{	// 縦OK
						for(let j=0;j<9;j++){
							this.lattice[j][this.start_index_x].verticalok = true;
						}
					}
				}
			}else if(this.start_index_y == this.end_index_y){	// 横線の場合
				if(this.dx > screen.width/6*5){	// 横のマスすべて通っている場合のみスワイプ判定する
					if((this.dy < -10) || (this.dy > 10)){	// 横線NG
						for(let i=0;i<6;i++){
							this.lattice[this.start_index_y][i].horizonng = true;
						}
					}else{	// 横線OK
						for(let i=0;i<6;i++){
							this.lattice[this.start_index_y][i].horizonok = true;
						}
					}
				}
			}

			clearInterval(document.interval);
			this.touch_time = 0;
		},
		tabChange: function(tab) {
			Object.assign(this.$data, initialState());
			this.Tab = tab;
			this.SettingWindow = false;
		},
		backButton: function() {
			this.SettingWindow = false;
		}
	},
})